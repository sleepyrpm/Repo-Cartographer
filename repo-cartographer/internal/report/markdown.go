package report

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/ayush-2007-iit/repo-cartographer/internal/contracts"
)

// Markdown renders the full markdown document for a report. It is
// deterministic for a given Report, and degrades gracefully when parts of the
// report are empty rather than printing hollow sections.
func Markdown(r contracts.Report) string {
	var b strings.Builder

	fmt.Fprintf(&b, "# Repo Cartography: %s\n\n", rootName(r.RootPath))

	if s := strings.TrimSpace(r.Summary); s != "" {
		b.WriteString(s + "\n\n")
	} else {
		b.WriteString("The agent produced no summary for this run.\n\n")
	}

	// --- Architecture -------------------------------------------------------
	b.WriteString("## Architecture\n\n")
	diagram := strings.TrimRight(fenceSafe(r.Diagram), "\n")
	if diagram == "" {
		b.WriteString("The agent did not gather enough structure to draw a diagram.\n\n")
	} else {
		if !strings.Contains(diagram, "-->") {
			b.WriteString("No import edges were resolved, so the diagram shows the files grouped by directory only.\n\n")
		}
		b.WriteString("```mermaid\n")
		b.WriteString(diagram + "\n")
		b.WriteString("```\n\n")
	}

	// --- Read these first ---------------------------------------------------
	b.WriteString("## Read these first\n\n")
	if len(r.Starters) == 0 {
		b.WriteString("The agent found no files it could confidently recommend as a starting point.\n\n")
	} else {
		for i, f := range r.Starters {
			note := strings.TrimSpace(f.Note)
			if note == "" {
				note = "recommended by the agent as an early read"
			}
			fmt.Fprintf(&b, "**%d.** `%s` — %s\n\n", i+1, f.Path, note)
		}
	}

	// --- Files the agent read ----------------------------------------------
	b.WriteString("## Files the agent read\n\n")
	if len(r.Visited) == 0 {
		b.WriteString("The agent did not open any files during this run.\n\n")
	} else {
		for _, p := range r.Visited {
			fmt.Fprintf(&b, "- `%s`\n", p)
		}
		b.WriteString("\n")
	}

	// --- Provenance ---------------------------------------------------------
	b.WriteString("---\n\n")
	if m := modelFromSummary(r.Summary); m != "" {
		fmt.Fprintf(&b, "Generated by Repo Cartographer. This report is the output of an autonomous observe-decide-act loop driven by the local open model `%s` via Ollama; no cloud API calls were made.\n", m)
	} else {
		b.WriteString("Generated by Repo Cartographer. This report is the output of an autonomous observe-decide-act loop driven by a local open model via Ollama; no cloud API calls were made.\n")
	}

	return b.String()
}

// fenceSafe makes sure the diagram can never close or nest the ```mermaid
// fence it is about to be placed inside.
func fenceSafe(diagram string) string {
	d := strings.TrimSpace(diagram)
	if d == "" {
		return ""
	}
	// Strip fences a caller may have wrapped the diagram in by mistake, then
	// neutralise any remaining backtick runs.
	d = strings.TrimPrefix(d, "```mermaid\n")
	d = strings.TrimSuffix(strings.TrimRight(d, "\n"), "```")
	d = strings.ReplaceAll(d, "```", "'''")
	return strings.TrimRight(d, "\n")
}

// modelFromSummary recovers the model name Build wrote into the summary, so
// the provenance footer can name it without contracts.Report carrying it.
func modelFromSummary(summary string) string {
	i := strings.Index(summary, modelSentinel)
	if i < 0 {
		return ""
	}
	rest := summary[i+len(modelSentinel):]
	j := strings.Index(rest, "`")
	if j <= 0 {
		return ""
	}
	return rest[:j]
}

// Write renders the report and writes it to path, creating parent directories
// as needed. The write goes to a temporary file in the same directory and is
// then renamed, so a reader never sees a half-written report.
func Write(path string, r contracts.Report) error {
	if strings.TrimSpace(path) == "" {
		return fmt.Errorf("report: write: empty path")
	}
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("report: create %s: %w", dir, err)
	}

	tmp, err := os.CreateTemp(dir, "."+filepath.Base(path)+".tmp*")
	if err != nil {
		return fmt.Errorf("report: temp file in %s: %w", dir, err)
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName) // no-op once the rename succeeded

	if _, err := tmp.WriteString(Markdown(r)); err != nil {
		tmp.Close()
		return fmt.Errorf("report: write %s: %w", tmpName, err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("report: close %s: %w", tmpName, err)
	}
	if err := os.Chmod(tmpName, 0o644); err != nil {
		return fmt.Errorf("report: chmod %s: %w", tmpName, err)
	}
	if err := os.Rename(tmpName, path); err != nil {
		return fmt.Errorf("report: rename to %s: %w", path, err)
	}
	return nil
}
