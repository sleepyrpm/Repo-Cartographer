package report

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// Mermaid node classes. Mid-tone fills with dark strokes and dark text, so the
// diagram stays legible on both light and dark backgrounds.
const (
	classStarter = "starter"
	classVisited = "visited"
	classPlain   = "plain"

	classDefStarter = "classDef starter fill:#f2b45c,stroke:#5a3a05,stroke-width:2px,color:#241a02"
	classDefVisited = "classDef visited fill:#8fc9d6,stroke:#0f3d47,stroke-width:2px,color:#0b2a31"
	classDefPlain   = "classDef plain fill:#c9ccd4,stroke:#343842,stroke-width:1px,color:#1b1e24"
)

// headerComment marks every diagram this package emits.
const headerComment = "%% generated by Repo Cartographer"

// Mermaid renders the architecture diagram as Mermaid source, WITHOUT ```
// fences. Files are grouped into subgraphs by directory, edges come from the
// resolved imports, and the starter and visited files are highlighted.
//
// The output is always valid Mermaid, including for empty input.
func Mermaid(in Input) string {
	set := nodeSet(in)
	edges := resolvedEdges(in, set)
	inDeg, outDeg := degrees(edges)

	starterRank := make(map[string]int)
	for i, f := range RankStarters(in) {
		p := normPath(f.Path)
		if p == "" {
			continue
		}
		if _, dup := starterRank[p]; !dup {
			starterRank[p] = i
		}
	}
	visited := make(map[string]bool)
	for _, v := range dedupStrings(in.Visited) {
		visited[v] = true
	}

	kept, omitted := selectNodes(sortedNodes(set), in.maxNodes(), starterRank, visited, inDeg, outDeg)

	var b strings.Builder
	b.WriteString(headerComment + "\n")
	b.WriteString("graph LR\n")

	if len(kept) == 0 {
		// Never emit an empty graph: a placeholder keeps the output renderable.
		b.WriteString("  empty[\"no files discovered\"]\n")
		b.WriteString("  " + classDefPlain + "\n")
		b.WriteString("  class empty plain\n")
		return b.String()
	}

	// Stable IDs: n1..nN assigned in sorted path order. Mermaid IDs cannot
	// contain "/", ".", "-", spaces or quotes, so the path only ever appears in
	// the (escaped) label.
	ids := make(map[string]string, len(kept))
	for i, p := range kept {
		ids[p] = "n" + strconv.Itoa(i+1)
	}

	// Group the kept nodes by directory, one subgraph per directory.
	byDir := make(map[string][]string)
	for _, p := range kept {
		d := dirOf(p)
		byDir[d] = append(byDir[d], p)
	}
	dirs := make([]string, 0, len(byDir))
	for d := range byDir {
		dirs = append(dirs, d)
	}
	sort.Strings(dirs)

	for i, d := range dirs {
		fmt.Fprintf(&b, "  subgraph sg%d[%s]\n", i+1, quoteLabel(d))
		members := byDir[d]
		sort.Strings(members)
		for _, p := range members {
			fmt.Fprintf(&b, "    %s[%s]\n", ids[p], quoteLabel(p))
		}
		b.WriteString("  end\n")
	}

	// Edges, already deduped and sorted; anything pointing at a node that was
	// truncated away is dropped so the diagram stays consistent.
	for _, e := range edges {
		from, okF := ids[e.From]
		to, okT := ids[e.To]
		if !okF || !okT {
			continue
		}
		fmt.Fprintf(&b, "  %s --> %s\n", from, to)
	}

	// Highlighting. Each node gets exactly one class: starter beats visited,
	// visited beats plain.
	var starters, vis, plain []string
	for _, p := range kept {
		switch {
		case hasKey(starterRank, p):
			starters = append(starters, ids[p])
		case visited[p]:
			vis = append(vis, ids[p])
		default:
			plain = append(plain, ids[p])
		}
	}
	b.WriteString("  " + classDefStarter + "\n")
	b.WriteString("  " + classDefVisited + "\n")
	b.WriteString("  " + classDefPlain + "\n")
	writeClass(&b, starters, classStarter)
	writeClass(&b, vis, classVisited)
	writeClass(&b, plain, classPlain)

	if omitted > 0 {
		fmt.Fprintf(&b, "  %%%% %d more files omitted\n", omitted)
	}
	return b.String()
}

// writeClass emits one `class a,b,c name` line, in node-ID order.
func writeClass(b *strings.Builder, ids []string, class string) {
	if len(ids) == 0 {
		return
	}
	sort.Slice(ids, func(i, j int) bool { return idNum(ids[i]) < idNum(ids[j]) })
	fmt.Fprintf(b, "  class %s %s\n", strings.Join(ids, ","), class)
}

// idNum extracts the numeric suffix of an "nNN" node ID.
func idNum(id string) int {
	n, err := strconv.Atoi(strings.TrimPrefix(id, "n"))
	if err != nil {
		return 0
	}
	return n
}

func hasKey(m map[string]int, k string) bool {
	_, ok := m[k]
	return ok
}

// quoteLabel renders a human path as a quoted Mermaid label, escaping the
// characters that would otherwise terminate the label early.
func quoteLabel(s string) string {
	s = strings.ReplaceAll(s, "\"", "&quot;")
	s = strings.ReplaceAll(s, "[", "&#91;")
	s = strings.ReplaceAll(s, "]", "&#93;")
	s = strings.ReplaceAll(s, "\n", " ")
	return "\"" + s + "\""
}

// selectNodes bounds the diagram to max nodes, keeping the ones that carry the
// most meaning: ranked starters first, then files the agent read, then the
// busiest nodes by degree, then the shallowest paths. It returns the kept
// paths in sorted order plus how many were dropped.
func selectNodes(all []string, max int, starterRank map[string]int, visited map[string]bool, inDeg, outDeg map[string]int) ([]string, int) {
	if len(all) <= max {
		return all, 0
	}

	// Importance is a single integer so the sort stays obvious and total.
	importance := func(p string) int {
		switch {
		case hasKey(starterRank, p):
			// Starters are never dropped, and keep their ranking order.
			return 1_000_000_000 - starterRank[p]
		case visited[p]:
			return 500_000 + 1_000*(inDeg[p]+outDeg[p]) - 10*depthOf(p)
		default:
			return 1_000*(inDeg[p]+outDeg[p]) - 10*depthOf(p)
		}
	}

	ranked := make([]string, len(all))
	copy(ranked, all)
	sort.SliceStable(ranked, func(i, j int) bool {
		a, bb := importance(ranked[i]), importance(ranked[j])
		if a != bb {
			return a > bb
		}
		return ranked[i] < ranked[j]
	})

	kept := ranked[:max]
	out := make([]string, len(kept))
	copy(out, kept)
	sort.Strings(out)
	return out, len(all) - max
}
